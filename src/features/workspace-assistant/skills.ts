export function discoverWorkspaceAssistantSkills(
  input: string,
  promptId?: string,
  additionalSkills: WorkspaceAssistantSkill[] = [],
): WorkspaceAssistantSkill[] {
  const normalized = `${promptId ?? ""} ${input}`.toLocaleLowerCase();
  const selected = new Set<string>(["monthly-plan-review"]);
  const registry = [...SKILLS, ...additionalSkills];
  for (const item of registry) {
    if (item.id === "monthly-plan-review") continue;
    if (item.triggers.some((trigger) => normalized.includes(trigger.toLocaleLowerCase()))) {
      selected.add(item.id);
    }
  }
  if (selected.size === 1 && /improv|suggest|recommend|تحسين|اقتراح/.test(normalized)) {
    selected.add("plan-improvement");
  }
  return registry.filter((item) => selected.has(item.id));
}

