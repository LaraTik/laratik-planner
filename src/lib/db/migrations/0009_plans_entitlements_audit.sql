-- ─── Append-only enforcement (hand-written) ────────────────────────────────
--
-- Single trigger function for both append-only tables. The function
-- raises an exception that names the offending table so the
-- application sees a clear message instead of a generic constraint
-- violation.
--
-- We use the trigger (vs. REVOKE UPDATE/DELETE on the app role)
-- because the entire application connects with a single DB role
-- (see PORT_NOTES.md — Supabase → plain Postgres sidecar). The
-- trigger is the structural enforcement that does not depend on
-- role-based separation.
CREATE OR REPLACE FUNCTION forbid_modify_audit_log() RETURNS TRIGGER AS $$
DECLARE
  tbl text := TG_TABLE_NAME;
  trg text := TG_NAME;
BEGIN
  IF TG_OP = 'UPDATE' THEN
    RAISE EXCEPTION
      'append-only table % forbids UPDATE (trigger %, row id=%)',
      tbl, trg, COALESCE(OLD.id::text, '<unknown>')
      USING ERRCODE = 'insufficient_privilege';
  ELSIF TG_OP = 'DELETE' THEN
    RAISE EXCEPTION
      'append-only table % forbids DELETE (trigger %, row id=%)',
      tbl, trg, COALESCE(OLD.id::text, '<unknown>')
      USING ERRCODE = 'insufficient_privilege';
  END IF;
  RETURN NULL;
END;
$$ LANGUAGE plpgsql;
