-- Migration 0009 — Plans, entitlements, usage thresholds, platform audit (M2.1)
--
-- Adds the data-model foundation for Milestone 2 of the StudioFlow
-- multi-agency build (docs/m2-multi-agency/PLAN.md). Five new tables
-- land in this migration:
--
--   1. platform_plan_template          — the 4 seeded plan tiers
--      (Starter / Growth / Enterprise / Custom). default_limits is a
--      JSONB blob of the documented limit shape; NULL for Custom.
--
--   2. agency_entitlement              — one row per agency. Holds the
--      plan choice + per-agency overrides + hard_stop_percent +
--      grace_policy. PK is agency_id, FK to platform_plan_template.
--
--   3. agency_entitlement_change       — APPEND-ONLY audit log of every
--      entitlement mutation. before / after are full snapshots of the
--      entitlement row. Triggers forbid UPDATE / DELETE.
--
--   4. agency_usage_threshold_event    — emitted by the usage-tracking
--      service (M2.3) when a counter crosses 80% / 90% / 100%.
--      UNIQUE (agency_id, resource, level) dedupes per-level events.
--
--   5. platform_audit_event            — APPEND-ONLY platform-level
--      audit log for every platform-admin action. Triggers forbid
--      UPDATE / DELETE.
--
-- Two enums:
--
--   agency_entitlement_grace_policy   — 'block' | 'allow_grace'
--   agency_usage_threshold_level      — 'warning' | 'urgent' | 'over_limit'
--
-- Append-only enforcement:
--
--   The two audit tables are made append-only via BEFORE UPDATE / BEFORE
--   DELETE triggers that RAISE EXCEPTION. The triggers are the single
--   source of truth — there is no separate GRANT to revoke (the app
--   uses one DB role for everything, see PORT_NOTES.md). The trigger
--   function is `forbid_modify_audit_log()`; it is re-usable for
--   future append-only tables (M2.7's platform_audit_event extensions
--   will use the same pattern).
--
-- Seed:
--
--   The 4 plan templates are seeded by this migration so the platform
--   console (M2.5+) has something to bind to. The seed is idempotent
--   (`ON CONFLICT (slug) WHERE archived_at IS NULL DO NOTHING`) so a
--   re-run after a partial failure is safe; it does not overwrite
--   edits made by an operator via the database console.
--
--   The default limits use the same key set the M2.2 service layer
--   expects (see schema/plans.ts comment block for the contract). The
--   Custom plan is the only one with NULL default_limits — it is a
--   sentinel meaning "no defaults; the agency must override every
--   limit at entitlement time."
--
-- Rollback:
--
--   DROP TABLE IF EXISTS platform_audit_event, agency_usage_threshold_event,
--     agency_entitlement_change, agency_entitlement, platform_plan_template
--     CASCADE;
--   DROP TYPE IF EXISTS agency_usage_threshold_level, agency_entitlement_grace_policy;
--   -- The trigger function is dropped automatically by CASCADE on the
--   -- tables that reference it; if any future table re-uses it, drop
--   -- it explicitly: DROP FUNCTION IF EXISTS forbid_modify_audit_log();
--
-- Note on a pre-existing schema/DB mismatch:
--
--   The brand_voice_workspace_archived_idx index was hand-added by
--   migration 0006 but is not declared in the Drizzle schema
--   (src/lib/db/schema/brand-kit.ts). Drizzle-kit's auto-diff
--   suggested dropping it; we explicitly keep it because the drop
--   would be an unrelated destructive change in an M2.1 migration
--   and the Drizzle schema mismatch is a pre-existing M1 issue.
--   Follow-up: align the Drizzle schema with the DB (either add
--   the index to brand-kit.ts or accept the drop in a separate
--   M1.10+ cleanup commit).

